/**
 * Community AI pipeline: classify → scope + permission checks → retrieve → generate → validate citations →
 * persist. The answer only ever cites sources that were actually retrieved for this viewer; any "[n]" the model
 * produces that doesn't map to a retrieved source is stripped before it is stored or shown.
 */
@Service
public class AiService {
    private static final Logger log = LoggerFactory.getLogger(AiService.class);
    private static final Pattern CITE = Pattern.compile("\\[(\\d{1,3})]");
    private static final int HISTORY_TURNS = 6;

    private final JdbcClient jdbc;
    private final Retriever retriever;
    private final HostedLlmProvider llm;
    private final OfflineProvider offline;
    private final CommunityRepository communities;
    private final CommunityAccess access;
    private final PostService posts;
    private final RateLimiter limiter;
    private final ObjectMapper json;
    private final String mode;

    public AiService(JdbcClient jdbc, Retriever retriever, HostedLlmProvider llm, OfflineProvider offline,
                     CommunityRepository communities, CommunityAccess access, PostService posts, RateLimiter limiter,
                     ObjectMapper json, AppProperties props) {
        this.jdbc = jdbc;
        this.retriever = retriever;
        this.llm = llm;
        this.offline = offline;
        this.communities = communities;
        this.access = access;
        this.posts = posts;
        this.limiter = limiter;
        this.json = json;
        this.mode = props.ai().provider() == null ? "auto" : props.ai().provider();
    }

    AiProvider provider() {
        if ("offline".equals(mode)) return offline;
        return llm.available() ? llm : offline;
    }

    public Status status() {
        AiProvider p = provider();
        boolean usesLlm = p == this.llm;
        return new Status(p.id(), p.label(), usesLlm, usesLlm
                ?"Answers are generated by an AI model from retrieved community discussions, with citations."
                : "No AI model is configured. Answers are cited summaries of retrieved discussions.");
    }

    // ------------------------------------------------------------------ ask

    /**
     * Deliberately not @Transactional: the model call can take many seconds and must not pin a database
     * connection. Each statement auto-commits; the question is stored before the call so it's never lost.
     */
    public AskResponse ask(AuthUser user, AskRequest req) {
        limiter.check("ai:ask:" + user.id(), 30, Duration.ofHours(1));
        String question = req.question().strip();
        if (question.length() < 3) throw ApiException.field("question", "Ask a slightly longer question");

        long conversationId;
        Scope scope;
        if (req.conversationId() != null) {
            ConvRow c = requireOwned(user, req.conversationId());
            conversationId = c.id();
            scope = resolveScope(user, req.communitySlug() != null ? req.communitySlug() : c.communitySlug(),
                    req.postId() != null ? req.postId() : c.postId(), req.sinceDays());
        } else {
            scope = resolveScope(user, req.communitySlug(), req.postId(), req.sinceDays());
            String title = question.length() > 120 ? question.substring(0, 119) + "…" : question;
            conversationId = jdbc.sql("INSERT INTO ai_conversations (user_id, title, community_id, post_id) VALUES (?, ?, ?, ?) RETURNING id")
                    .params(user.id(), title, scope.communityId(), scope.postId()).query(Long.class).single();
        }

        List<Turn> history = history(conversationId);
        Intent intent = QueryAnalyzer.intent(question);
        List<Source> sources = retriever.retrieve(question, intent, scope, user.id());
        long questionId = insertMessage(conversationId, "USER", question, null, null, List.of(), List.of(), null, null, null);

        AiProvider provider = provider();
        Answer answer;
        String engine = provider.label();
        try {
            answer = provider.answer(new AiProvider.Request(question, intent, sources, history, scopeNote(scope)));
        } catch (RuntimeException e) {
            log.warn("AI provider {} failed ({}); falling back to offline retrieval", provider.id(), e.getClass().getSimpleName());
            answer = offline.answer(new AiProvider.Request(question, intent, sources, history, scopeNote(scope)));
            answer = new Answer(answer.text(), answer.followUps(),
                    "The AI model couldn't be reached, so this is a cited summary of the retrieved discussions instead.", null, null);
            engine = offline.label();
        }

        Validated v = validateCitations(answer.text(), sources);
        String notice = answer.notice();
        if (sources.isEmpty() && notice == null) notice = "No matching community discussions were found for this question.";
        else if (!sources.isEmpty() && sources.size() < 3 && notice == null) notice = "Only a few relevant discussions were found; treat this answer as limited.";

        long answerId = insertMessage(conversationId, "ASSISTANT", v.text(), engine, intent.name(), v.sources(), answer.followUps(),
                notice, answer.inputTokens(), answer.outputTokens());
        jdbc.sql("UPDATE ai_conversations SET updated_at = now() WHERE id = ?").param(conversationId).update();

        ConvRow conv = requireOwned(user, conversationId);
        return new AskResponse(summary(conv), message(questionId, user.id()), message(answerId, user.id()));
    }

    record Validated(String text, List<Source> sources) {}

    /** Strip citations that don't map to a retrieved source; mark the sources that were actually cited. */
    static Validated validateCitations(String text, List<Source> sources) {
        Set<Integer> cited = new TreeSet<>();
        Matcher m = CITE.matcher(text);
        StringBuilder out = new StringBuilder();
        while (m.find()) {
            int n = Integer.parseInt(m.group(1));
            if (n >= 1 && n <= sources.size()) {
                cited.add(n);
                m.appendReplacement(out, Matcher.quoteReplacement(m.group()));
            } else {
                m.appendReplacement(out, "");
            }
        }
        m.appendTail(out);
        List<Source> marked = sources.stream().map(s -> new Source(s.n(), s.kind(), s.postId(), s.commentId(), s.title(),
                s.communitySlug(), s.author(), s.score(), s.createdAt(), s.excerpt(), s.link(), cited.contains(s.n()))).toList();
        return new Validated(out.toString().replaceAll("[ \\t]+\\n", "\n").strip(), marked);
    }

    private Scope resolveScope(AuthUser user, String communitySlug, Long postId, Integer sinceDays) {
        Long communityId = null;
        String slug = null;
        String postTitle = null;
        if (communitySlug != null && !communitySlug.isBlank()) {
            Community c = communities.findBySlug(communitySlug).orElseThrow(() -> ApiException.field("communitySlug", "Community not found"));
            access.requireView(c, user);
            communityId = c.getId();
            slug = c.getSlug();
        }
        if (postId != null) {
            var ctx = posts.context(postId, user); // throws 403/404 when the viewer can't see it
            if (!ctx.post().isLive()) throw ApiException.notFound("Post");
            postTitle = ctx.post().getTitle();
        }
        return new Scope(communityId, slug, postId, postTitle, sinceDays);
    }

    private static String scopeNote(Scope s) {
        List<String> parts = new ArrayList<>();
        if (s.postTitle() != null) parts.add("questions about the thread \"" + s.postTitle() + "\" (its post and comments are included)");
        if (s.communitySlug() != null) parts.add("limited to c/" + s.communitySlug());
        if (s.sinceDays() != null) parts.add("discussions from the last " + s.sinceDays() + " days");
        return parts.isEmpty() ? null : String.join("; ", parts);
    }

    private List<Turn> history(long conversationId) {
        List<Turn> turns = jdbc.sql("SELECT role, content FROM ai_messages WHERE conversation_id = ? ORDER BY id DESC LIMIT ?")
                .params(conversationId, HISTORY_TURNS)
                .query((rs, i) -> new Turn(rs.getString(1), rs.getString(2))).list();
        List<Turn> ordered = new ArrayList<>(turns);
        Collections.reverse(ordered);
        // The API expects alternating turns starting with the user.
        while (!ordered.isEmpty() && !"USER".equals(ordered.getFirst().role())) ordered.removeFirst();
        if (!ordered.isEmpty() && "USER".equals(ordered.getLast().role())) ordered.removeLast();
        return ordered;
    }

    private long insertMessage(long conversationId, String role, String content, String engine, String intent,
                               List<Source> sources, List<String> followUps, String notice, Integer in, Integer out) {
        return jdbc.sql("""
                        INSERT INTO ai_messages (conversation_id, role, content, engine, intent, sources, follow_ups, notice,
                                                 input_tokens, output_tokens)
                        VALUES (?, ?, ?, ?, ?, CAST(? AS jsonb), CAST(? AS jsonb), ?, ?, ?) RETURNING id""")
                .params(conversationId, role, content, engine, intent, write(sources), write(followUps), notice, in, out)
                .query(Long.class).single();
    }

    // ------------------------------------------------------------------ conversations

    private record ConvRow(long id, long userId, String title, String communitySlug, Long postId, Instant createdAt, Instant updatedAt) {}

    private ConvRow requireOwned(AuthUser user, long id) {
        ConvRow c = jdbc.sql("""
                        SELECT a.id, a.user_id, a.title, cm.slug, a.post_id, a.created_at, a.updated_at
                        FROM ai_conversations a LEFT JOIN communities cm ON cm.id = a.community_id WHERE a.id = ?""")
                .param(id)
                .query((rs, i) -> new ConvRow(rs.getLong(1), rs.getLong(2), rs.getString(3), rs.getString(4), (Long) rs.getObject(5),
                        rs.getObject(6, OffsetDateTime.class).toInstant(), rs.getObject(7, OffsetDateTime.class).toInstant()))
                .optional().orElseThrow(() -> ApiException.notFound("Conversation"));
        if (c.userId() != user.id()) throw ApiException.notFound("Conversation");
        return c;
    }

    private static ConversationSummary summary(ConvRow c) {
        return new ConversationSummary(c.id(), c.title(), c.communitySlug(), c.postId(), c.updatedAt());
    }

    @Transactional(readOnly = true)
    public List<ConversationSummary> list(AuthUser user) {
        return jdbc.sql("""
                        SELECT a.id, a.title, cm.slug, a.post_id, a.updated_at FROM ai_conversations a
                        LEFT JOIN communities cm ON cm.id = a.community_id WHERE a.user_id = ? ORDER BY a.updated_at DESC LIMIT 100""")
                .param(user.id())
                .query((rs, i) -> new ConversationSummary(rs.getLong(1), rs.getString(2), rs.getString(3), (Long) rs.getObject(4),
                        rs.getObject(5, OffsetDateTime.class).toInstant()))
                .list();
    }

    @Transactional(readOnly = true)
    public ConversationDto get(AuthUser user, long id) {
        ConvRow c = requireOwned(user, id);
        List<Long> ids = jdbc.sql("SELECT id FROM ai_messages WHERE conversation_id = ? ORDER BY id").param(id).query(Long.class).list();
        List<MessageDto> messages = ids.stream().map(mid -> message(mid, user.id())).toList();
        return new ConversationDto(c.id(), c.title(), c.communitySlug(), c.postId(), c.createdAt(), messages);
    }

    @Transactional
    public void delete(AuthUser user, long id) {
        requireOwned(user, id);
        jdbc.sql("DELETE FROM ai_conversations WHERE id = ?").param(id).update();
    }

    @Transactional
    public void feedback(AuthUser user, long messageId, int value) {
        Long owner = jdbc.sql("""
                        SELECT a.user_id FROM ai_messages m JOIN ai_conversations a ON a.id = m.conversation_id
                        WHERE m.id = ? AND m.role = 'ASSISTANT'""")
                .param(messageId).query(Long.class).optional().orElseThrow(() -> ApiException.notFound("Answer"));
        if (owner != user.id()) throw ApiException.notFound("Answer");
        jdbc.sql("UPDATE ai_messages SET feedback = ? WHERE id = ?").params(value, messageId).update();
    }

    /**
     * Stored sources are snapshots. When an old answer is re-read, sources whose post has since been deleted or
     * removed, or moved out of the viewer's reach (e.g. a community went private), are redacted.
     */
    private MessageDto message(long id, long viewerId) {
        record Row(long id, String role, String content, String engine, String intent, String sources, String followUps,
                   String notice, int feedback, Instant createdAt) {}
        Row r = jdbc.sql("""
                        SELECT id, role, content, engine, intent, sources::text, follow_ups::text, notice, feedback, created_at
                        FROM ai_messages WHERE id = ?""")
                .param(id)
                .query((rs, i) -> new Row(rs.getLong(1), rs.getString(2), rs.getString(3), rs.getString(4), rs.getString(5),
                        rs.getString(6), rs.getString(7), rs.getString(8), rs.getInt(9), rs.getObject(10, OffsetDateTime.class).toInstant()))
                .single();
        List<Source> sources = read(r.sources(), new TypeReference<List<Source>>() {});
        if (!sources.isEmpty()) {
            Set<Long> visible = new HashSet<>(jdbc.sql("""
                            SELECT p.id FROM posts p JOIN communities cm ON cm.id = p.community_id
                            WHERE p.id IN (:ids) AND p.deleted_at IS NULL AND p.removed = FALSE
                              AND (cm.visibility <> 'PRIVATE' OR EXISTS (SELECT 1 FROM community_members vm
                                   WHERE vm.community_id = cm.id AND vm.user_id = :viewer))""")
                    .param("ids", sources.stream().map(Source::postId).distinct().toList()).param("viewer", viewerId)
                    .query(Long.class).list());
            sources = sources.stream().map(s -> visible.contains(s.postId()) ? s
                    : new Source(s.n(), s.kind(), s.postId(), s.commentId(), "[no longer available]", s.communitySlug(), null, 0,
                    s.createdAt(), "This source was deleted or is no longer visible to you.", null, s.cited())).toList();
        }
        return new MessageDto(r.id(), r.role(), r.content(), r.engine(), r.intent(), sources,
                read(r.followUps(), new TypeReference<List<String>>() {}), r.notice(), r.feedback(), r.createdAt());
    }

    private String write(Object o) {
        try {
            return json.writeValueAsString(o);
        } catch (JsonProcessingException e) {
            throw new IllegalStateException(e);
        }
    }

    private <T> T read(String s, TypeReference<T> type) {
        try {
            return json.readValue(s, type);
        } catch (JsonProcessingException e) {
            throw new IllegalStateException(e);
        }
    }
}
