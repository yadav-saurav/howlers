/** A real 16-bit mono PCM WAV of a quiet 440 Hz tone. Honest test media, never presented as a real episode. */
function toneWav(seconds: number, rate = 8000): Buffer {
  const samples = seconds * rate;
  const data = Buffer.alloc(samples * 2);
  for (let i = 0; i < samples; i++) data.writeInt16LE(Math.round(Math.sin((2 * Math.PI * 440 * i) / rate) * 3000), i * 2);
  const h = Buffer.alloc(44);
  h.write('RIFF', 0); h.writeUInt32LE(36 + data.length, 4); h.write('WAVE', 8);
  h.write('fmt ', 12); h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(1, 22);
  h.writeUInt32LE(rate, 24); h.writeUInt32LE(rate * 2, 28); h.writeUInt16LE(2, 32); h.writeUInt16LE(16, 34);
  h.write('data', 36); h.writeUInt32LE(data.length, 40);
  return Buffer.concat([h, data]);
}

/**
 * The published episode to play. The local demo database has a hand-made one; a fresh database (CI) has none, because
 * the demo seed never invents media. Then the community's owner publishes a clearly labelled test-tone episode through
 * the real studio endpoints (upload, transcript, review, publish).
 */
async function publishedEpisode(api: Api): Promise<{ title: string; createdId?: number }> {
  const page = await api.get<{ items: { title: string }[] }>('/podcasts?sort=recent');
  if (page.items.length && !process.env.E2E_FORCE_TEST_EPISODE) return { title: page.items[0].title };
  const title = `E2E test tone ${uid()} (generated by the test suite)`;
  const ep = await api.post<{ id: number }>('/communities/programming/podcasts/episodes', {
    title, summary: 'A 20-second sine tone uploaded by the end-to-end suite to exercise the player. Not a real episode.', type: 'HIGHLIGHTS',
  });
  await api.upload(`/podcasts/episodes/${ep.id}/media`, { name: 'tone.wav', mimeType: 'audio/wav', buffer: toneWav(20) }, { durationSeconds: '20' });
  await api.put(`/podcasts/episodes/${ep.id}/transcript`, { format: 'timestamped', content: '[00:00:00] Test: a 440 Hz tone, no speech.' });
  await api.post(`/podcasts/episodes/${ep.id}/submit`);
  await api.post(`/podcasts/episodes/${ep.id}/publish`);
  return { title, createdId: ep.id };
}

test('19 · play a seeded podcast episode', async ({ sessions }) => {
  const studio = await sessions.api('mira_k');
  const { title, createdId } = await publishedEpisode(studio);
  // A test-tone episode made above is removed afterwards, so it never lingers in listings.
  if (createdId) test.info().attach('created-episode', { body: String(createdId) });
  try {
    await playEpisode(sessions, title);
  } finally {
    if (createdId) await studio.delete(`/podcasts/episodes/${createdId}`);
  }
});

async function playEpisode(sessions: Sessions, title: string) {
  const page = await sessions.open('tunde_builds', '/podcasts');
  await page.getByRole('heading', { level: 2, name: 'All episodes' }).waitFor();
  await page.getByRole('link', { name: new RegExp(title.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')) }).first().click();
  await expect(page.getByRole('heading', { level: 1, name: title })).toBeVisible();

  await page.getByRole('button', { name: /^(Play episode|Resume from)/ }).click();
  const player = page.getByRole('region', { name: 'Podcast player' });
  await expect(player).toBeVisible();
  await expect(player.getByRole('button', { name: 'Pause' })).toBeVisible();

  // Start from the top so the position has room to advance, then watch it move.
  const seek = player.getByRole('slider', { name: 'Seek' });
  await seek.fill('0');
  const position = async () => Number(await seek.inputValue());
  const start = await position();
  await expect.poll(position, { timeout: 15_000 }).toBeGreaterThanOrEqual(start + 2);
  await expect(seek).toHaveAttribute('aria-valuetext', /^\d+:\d{2} of \d+:\d{2}$/);

  await player.getByRole('button', { name: 'Pause' }).click();
  await expect(player.getByRole('button', { name: 'Play', exact: true })).toBeVisible();
}

test('20 · contribute to moderator support (demo mode)', async ({ sessions }) => {
  // Arrange: an open pool in c/programming (moderators may keep up to 3 open) and membership for the contributor.
  const mod = await sessions.api('mira_k');
  type Funding = { pools: { id: number; title: string; status: string }[] };
  const funding = await mod.get<Funding>('/communities/programming/funding');
  let pool = funding.pools.find((p) => p.status === 'OPEN' && p.title.startsWith('E2E'));
  if (!pool) {
    const end = new Date(Date.now() + 30 * 86_400_000).toISOString();
    pool = await mod.post<{ id: number; title: string; status: string }>('/communities/programming/funding/pools', {
      title: `E2E moderator support ${uid()}`,
      purpose: 'Created by the end-to-end suite to exercise demo contributions.',
      currency: 'USD',
      goalMinor: 50_000,
      periodEnd: end,
    });
  }
  const member = await sessions.api('dev_ostrander');
  const c = await member.get<{ viewer: { isMember: boolean } }>('/communities/programming');
  if (!c.viewer.isMember) await member.post('/communities/programming/membership');

  const page = await sessions.open('dev_ostrander', '/c/programming?view=funding');
  await expect(page.getByRole('note', { name: 'DEMO, no real money' })).toBeVisible();
  const card = page.getByRole('article', { name: pool.title });
  await card.getByRole('button', { name: 'Contribute (demo)' }).click();

  const dialog = page.getByRole('dialog', { name: `Contribute to “${pool.title}”` });
  await expect(dialog.getByText('DEMO, no real money').first()).toBeVisible();
  await dialog.getByRole('textbox', { name: /Other amount/ }).fill('7');
  await dialog.getByRole('button', { name: 'Contribute $7.00 (demo)' }).click();
  await expect(page.getByText('Demo contribution recorded. No real money moved.')).toBeVisible();

  // It shows up under My contributions, labelled as demo.
  await page.getByRole('link', { name: 'My contributions' }).click();
  await expect(page).toHaveURL(/\/funding$/);
  const mine = page.getByRole('region', { name: 'My contributions' });
  await expect(mine.getByText(pool.title).first()).toBeVisible();
  await expect(mine.getByText(/^Demo/).first()).toBeVisible();
});

test('21 · view the leaderboard', async ({ sessions }) => {
  const page = await sessions.open('paperback_jo', '/leaderboard');
  await expect(page.getByRole('heading', { level: 1, name: 'Leaderboard' })).toBeVisible();
  await expect(page.getByRole('tab', { name: 'Moderators' })).toHaveAttribute('aria-selected', 'true');
  const ranking = page.getByRole('list', { name: /^Moderator ranking for / });
  const empty = page.getByRole('heading', { name: /^No ranked moderators for / });
  // Scores come from real moderation activity only: a fresh database (CI) can honestly have nobody ranked yet.
  await expect(ranking.or(empty)).toBeVisible();
  if (await ranking.isVisible()) {
    const row = ranking.getByRole('listitem').first();
    await expect(row.getByRole('link', { name: /^u\// })).toBeVisible();
    // The score breakdown opens from a disclosure button and explains the formula.
    const toggle = row.getByRole('button', { name: /^Score breakdown for u\// });
    await expect(toggle).toHaveAttribute('aria-expanded', 'false');
    await toggle.click();
    await expect(toggle).toHaveAttribute('aria-expanded', 'true');
    await expect(row.getByText(/Consistency/).first()).toBeVisible();
  }
  // The formula is always public.
  await expect(page.getByRole('heading', { name: 'How the score works' })).toBeVisible();

  await page.getByRole('tab', { name: 'Topics' }).click();
  await expect(page.getByRole('tab', { name: 'Topics' })).toHaveAttribute('aria-selected', 'true');
});
